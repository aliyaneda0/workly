-- Baseline schema for review-service's own database: just the review table, carved out of the
-- monolith's V1__init.sql. No company/job/app_user/refresh_token tables here — company_id is a
-- plain column, not a foreign key, since company now lives in a different database entirely
-- (see Review.java — company existence is checked over HTTP via CompanyClient instead).

create table review (
    id bigint generated by default as identity primary key,
    title varchar(255),
    description varchar(255),
    rating float(53) not null,
    reviewed_by bigint,
    company_id bigint
);
