-- Baseline schema for job-service's own database: just the job table, carved out of the
-- monolith's V1__init.sql. No company/review/app_user/refresh_token tables here — company_id
-- is a plain column, not a foreign key, since company now lives in a different database
-- entirely (see Job.java — company existence is checked over HTTP via CompanyClient instead).

create table job (
    id bigint generated by default as identity primary key,
    title varchar(255),
    description varchar(255),
    location varchar(255),
    min_salary numeric(38,2),
    max_salary numeric(38,2),
    status smallint check (status between 0 and 2),
    posted_by bigint,
    company_id bigint
);
