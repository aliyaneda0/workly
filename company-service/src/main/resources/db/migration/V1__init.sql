-- Baseline schema for company-service's own database: just the company table, carved out of
-- the monolith's V1__init.sql. No job/review/app_user/refresh_token tables here — those stay
-- in the monolith's database until their own turn to be extracted.

create table company (
    id bigint generated by default as identity primary key,
    company_name varchar(255),
    location varchar(255),
    description varchar(255)
);
